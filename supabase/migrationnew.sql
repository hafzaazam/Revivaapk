-- -----------------------------------------------------
-- 1. extensions & enum types
-- -----------------------------------------------------
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- enums used across tables
CREATE TYPE public.category_status AS ENUM ('active', 'hidden');
CREATE TYPE public.product_status AS ENUM ('draft', 'active', 'archived');
CREATE TYPE public.order_status AS ENUM ('pending', 'confirmed', 'processing', 'shipped', 'delivered', 'cancelled', 'refunded');
CREATE TYPE public.payment_status AS ENUM ('unpaid', 'paid', 'refunded');
CREATE TYPE public.review_status AS ENUM ('pending', 'approved', 'rejected');

-- -----------------------------------------------------
-- 2. categories
-- -----------------------------------------------------
CREATE TABLE IF NOT EXISTS public.categories (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    name TEXT NOT NULL,
    slug TEXT NOT NULL UNIQUE,
    description TEXT,
    image_url TEXT,                     -- optional path/URL to an image
    parent_category_id UUID REFERENCES public.categories(id) ON DELETE SET NULL,
    display_order INTEGER NOT NULL DEFAULT 0,
    status category_status NOT NULL DEFAULT 'active',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- trigger to keep updated_at up‑to‑date
CREATE OR REPLACE FUNCTION public.handle_updated_at()
RETURNS TRIGGER AS $$ BEGIN
    NEW.updated_at = now();
    RETURN NEW; END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER handle_categories_updated
BEFORE UPDATE ON public.categories
FOR EACH ROW EXECUTE FUNCTION public.handle_updated_at();

-- -----------------------------------------------------
-- 3. product_categories (many‑to‑many)
-- -----------------------------------------------------
CREATE TABLE IF NOT EXISTS public.product_categories (
    product_id UUID REFERENCES public.products(id) ON DELETE CASCADE,
    category_id UUID REFERENCES public.categories(id) ON DELETE CASCADE,
    PRIMARY KEY (product_id, category_id)
);

-- -----------------------------------------------------
-- 4. products
-- -----------------------------------------------------
CREATE TABLE IF NOT EXISTS public.products (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    name TEXT NOT NULL,
    slug TEXT NOT NULL UNIQUE,
    short_description TEXT,               -- for cards/listings
    description TEXT,                       -- rich text / markdown (kept simple as TEXT)
    price_cents INTEGER NOT NULL,         -- store in cents to avoid float bugs
    compare_at_cents INTEGER,             -- null = no discount
    sku TEXT UNIQUE,
    stock_quantity INTEGER NOT NULL DEFAULT 0,
    status product_status NOT NULL DEFAULT 'draft',
    -- primary image (URL or path); other images stored in product_images
    primary_image_url TEXT,
    -- rating denormalized fields
    rating_average NUMERIC(3,2) NOT NULL DEFAULT 0,
    rating_count INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE OR REPLACE FUNCTION handle_products_updated()
RETURNS TRIGGER AS $$ BEGIN
    NEW.updated_at = now();
    RETURN NEW; END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER handle_products_updated_trig
BEFORE UPDATE ON public.products
FOR EACH ROW EXECUTE FUNCTION public.handle_products_updated();

-- -----------------------------------------------------
-- 5. product_variants (optional size / scent)
-- -----------------------------------------------------
CREATE TABLE IF NOT EXISTS public.product_variants (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    product_id UUID REFERENCES public.products(id) ON DELETE CASCADE,
    -- free‑form description, e.g. "Size: 250 ml, Scent: Lavender"
    option_text TEXT NOT NULL,
    price_cents INTEGER NOT NULL DEFAULT 0,   -- override/add to base price
    stock_quantity INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (id)
);

-- -----------------------------------------------------
-- 6. product_images (extra images beyond the primary)
-- -----------------------------------------------------
CREATE TABLE IF NOT EXISTS public.product_images (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    product_id UUID REFERENCES public.products(id) ON DELETE CASCADE,
    url TEXT NOT NULL,               -- storage path or CDN URL
    is_primary BOOLEAN NOT NULL DEFAULT FALSE,
    display_order INTEGER NOT NULL DEFAULT 0
);

-- -----------------------------------------------------
-- 7. orders
-- -----------------------------------------------------
CREATE TABLE IF NOT EXISTS public.orders (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    order_number TEXT NOT NULL UNIQUE,       -- e.g. "#1024", generated by a trigger
    customer_name TEXT NOT NULL,
    customer_email TEXT NOT NULL,
    customer_phone TEXT,
    shipping_address JSONB NOT NULL,         -- {street, city, province, postal_code, country}
    billing_address JSONB,                   -- optional, can be same as shipping
    payment_method TEXT,                     -- e.g. "credit_card", "paypal"
    payment_status public.payment_status NOT NULL DEFAULT 'unpaid',
    subtotal_cents INTEGER NOT NULL DEFAULT 0,
    shipping_cents INTEGER NOT NULL DEFAULT 0,
    tax_cents INTEGER NOT NULL DEFAULT 0,
    total_cents INTEGER NOT NULL DEFAULT 0,
    status public.order_status NOT NULL DEFAULT 'pending',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    status_history JSONB NOT NULL DEFAULT '[]'::jsonb   -- [{status, note, timestamp}, ...]
);

CREATE OR REPLACE FUNCTION handle_orders_updated()
RETURNS TRIGGER AS $$ BEGIN
    NEW.updated_at = now();
    -- persist the new status into history
    NEW.status_history := COALESCE(NEW.status_history, '[]'::jsonb) || jsonb_build_object(
        'status', NEW.status,
        'note', NULL,
        'timestamp', now()
    );
    RETURN NEW; END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER handle_orders_updated_trig
BEFORE UPDATE ON public.orders
FOR EACH ROW EXECUTE FUNCTION public.handle_orders_updated();

-- -----------------------------------------------------
-- 8. order_lines (line_items)
-- -----------------------------------------------------
CREATE TABLE IF NOT EXISTS public.order_lines (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    order_id UUID REFERENCES public.orders(id) ON DELETE CASCADE,
    product_id UUID REFERENCES public.products(id),
    variant_id UUID REFERENCES public.product_variants(id),   -- null if no variant
    quantity INTEGER NOT NULL DEFAULT 1,
    price_cents INTEGER NOT NULL,            -- snapshot at purchase
    total_cents INTEGER NOT NULL             /* quantity * price_cents */,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- -----------------------------------------------------
-- 9. reviews
-- -----------------------------------------------------
CREATE TABLE IF NOT EXISTS public.reviews (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    product_id UUID REFERENCES public.products(id) ON DELETE CASCADE,
    customer_name TEXT NOT NULL,
    customer_email TEXT NOT NULL,            -- not displayed publicly, used for verification
    rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
    title TEXT,                               -- optional
    body TEXT NOT NULL,
    image_url TEXT,                           -- optional photo
    status review_status NOT NULL DEFAULT 'pending',
    verified_purchase BOOLEAN NOT NULL DEFAULT FALSE,
    admin_reply TEXT,
    admin_replied_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE OR REPLACE FUNCTION handle_reviews_updated_at()
RETURNS TRIGGER AS $$ BEGIN
    NEW.admin_replied_at := CASE WHEN NEW.admin_reply IS NOT NULL THEN now() ELSE NULL END;
    NEW.updated_at := now();   -- we’ll be handled by a generic trigger if you add one
    RETURN NEW; END;
$$ LANGUAGE plpgsql;

-- generic updated_at trigger (same pattern as categories/products)
CREATE OR REPLACE FUNCTION handle_reviews_updated_at_trig()
RETURNS TRIGGER AS $$ BEGIN
    NEW.updated_at = now();
    RETURN NEW; END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER handle_reviews_updated_trig
BEFORE UPDATE ON public.reviews
FOR EACH ROW EXECUTE FUNCTION public.handle_reviews_updated_at_trig();

-- -----------------------------------------------------
-- 10. helpers / indexes
-- -----------------------------------------------------
-- make slug look‑ups faster
CREATE UNIQUE INDEX idx_products_slug ON public.products (lower(slug));
CREATE UNIQUE INDEX idx_categories_slug ON public.categories (lower(slug));

-- help order‑line look‑ups
CREATE INDEX idx_order_lines_order ON public.order_lines (order_id);
CREATE INDEX idx_order_lines_product ON public.order_lines (product_id);

-- review list queries
CREATE INDEX idx_reviews_product ON public.reviews (product_id);
CREATE INDEX idx_reviews_status ON public.reviews (status);

